const entries = [];
for (const [st, cities] of Object.entries(BY_STATE)) {
  for (const c of cities) {
    const key = String(c).toLowerCase().trim();
    if (!key) continue;
    if (!entries.some((e) => e[0] === key)) entries.push([key, st]);
  }
}

/** @type {Map<string, string>} */
export const CITY_DEFAULT_STATE = new Map(entries);

/** Longest city names first so e.g. "san jose" wins over "san". */
const CITY_KEYS_BY_LENGTH = [...CITY_DEFAULT_STATE.keys()].sort((a, b) => b.length - a.length);

/**
 * Infer U.S. state from a free-text city / area string (no ", ST" required).
 * @param {string} hint
 * @returns {string|null} two-letter state or null
 */
export function inferStateFromCityHint(hint) {
  if (!hint || typeof hint !== "string") return null;
  const h = hint
    .toLowerCase()
    .replace(/\b\d{5}(?:-\d{4})?\b/g, "")
    .replace(/\s+/g, " ")
    .trim();
  if (!h) return null;
  for (const city of CITY_KEYS_BY_LENGTH) {
    if (h === city || h.startsWith(`${city} `) || h.startsWith(`${city},`)) {
      return CITY_DEFAULT_STATE.get(city) || null;
    }
  }
  return null;
}
